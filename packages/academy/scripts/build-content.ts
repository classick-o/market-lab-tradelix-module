// Writes src/generated from the course content: metadata loaded with the app, scripts loaded per unit.
// Run: npm run content:build (also runs before dev, build and test).
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compileCourseContent, unitFile } from "../src/content/compile";

const out = join(dirname(fileURLToPath(import.meta.url)), "../src/generated");
const scriptsDir = join(out, "scripts");
mkdirSync(scriptsDir, { recursive: true });
for (const f of readdirSync(scriptsDir)) rmSync(join(scriptsDir, f));

const { meta, scripts } = compileCourseContent();
const header = "// Generated by packages/academy/scripts/build-content.ts. Don't edit by hand.\n";
// JSON.parse of a string literal parses faster than an object literal of the same size.
const asModule = (value: unknown) => `${header}export default JSON.parse(${JSON.stringify(JSON.stringify(value))});\n`;

writeFileSync(join(out, "course-meta.js"), asModule(meta));
writeFileSync(
  join(out, "course-meta.d.ts"),
  `${header}import type { Concept, GlossaryTerm, Lesson, Question } from "../types";\ndeclare const meta: { lessons: Lesson[]; questions: Question[]; terms: GlossaryTerm[]; concepts: Concept[] };\nexport default meta;\n`,
);

const units = Object.keys(scripts).sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
for (const unit of units) {
  writeFileSync(join(scriptsDir, `${unitFile(unit)}.js`), asModule(scripts[unit]));
  writeFileSync(join(scriptsDir, `${unitFile(unit)}.d.ts`), `${header}import type { LessonScript } from "../../types";\ndeclare const scripts: Record<string, LessonScript>;\nexport default scripts;\n`);
}
writeFileSync(
  join(out, "script-loaders.ts"),
  `${header}import type { LessonScript } from "../types";\n\n/** Loads the scripts of one unit; bundlers put each unit in its own chunk. */\nexport const SCRIPT_LOADERS: Record<string, () => Promise<{ default: Record<string, LessonScript> }>> = {\n${units.map((u) => `  "${u}": () => import("./scripts/${unitFile(u)}"),`).join("\n")}\n};\n`,
);
console.log(`lessons ${meta.lessons.length}, questions ${meta.questions.length}, terms ${meta.terms.length}, concepts ${meta.concepts.length}, script units ${units.length}`);
