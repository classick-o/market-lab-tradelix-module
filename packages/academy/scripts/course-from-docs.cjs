// Builds src/course/map.ts from the course map in docs/learn/course (levels, units, lesson cards).
// Run: node packages/academy/scripts/course-from-docs.cjs
// Only the English parts of a card reach the app: titles, objectives, ids. Notes stay in the docs.
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "../../..");
const dir = path.join(root, "docs/learn/course");
const out = path.join(root, "packages/academy/src/course/map.ts");
const files = ["level-0-orientation.md", "level-1-foundations.md", "level-2-practitioner-a.md", "level-2-practitioner-b.md", "level-3-advanced-a.md", "level-3-advanced-b.md", "level-4-professional.md"];

const field = (card, name) => {
  const m = card.match(new RegExp(`\\*\\*${name.replace(/[/]/g, "\\/")}:\\*\\*([^\\n]*)`));
  return m ? m[1].trim() : "";
};
const ids = (text) => [...text.matchAll(/`?([a-z0-9][a-z0-9-]*[a-z0-9])`?/g)].map((m) => m[1]).filter((x) => !["nou", "new"].includes(x));

const TRACKS = ["Price action and order flow", "Macro and news", "Technical analyst", "Systematic trader", "Derivatives"];
const units = new Map();
const lessons = [];
for (const f of files) {
  const text = fs.readFileSync(path.join(dir, f), "utf8").replace(/\r\n/g, "\n");
  for (const m of text.matchAll(/^## (?:Unitatea )?(\d)\.(\d{1,2}) · (.+)$/gm)) {
    const id = `${m[1]}.${m[2]}`;
    const title = m[3].replace(/\s*\(\d+ lecții[^)]*\)\s*$/, "").replace(/\s*·\s*\d+ lecții\s*$/, "").trim();
    if (!units.has(id)) units.set(id, { id, level: Number(m[1]), title });
  }
  for (const part of text.split(/\n(?=#### \d+\.\d+\.\d+ )/)) {
    const h = part.match(/^#### (\d+)\.(\d+)\.(\d+) · (.+?)(?:\s+·\s+`(L\d+)`)?\s*$/m);
    if (!h) continue;
    const card = part.split(/\n#{2,4} /)[0];
    const meta = field(card, "Nivel / durată / tip");
    const [stage, mins, kindRaw = "Core"] = meta.split("·").map((s) => s.trim());
    const kindM = kindRaw.match(/^(Core|Track|Elective|Electivă)(?:\s*\(([^)]+)\))?/);
    const kind = !kindM || kindM[1] === "Core" ? "core" : kindM[1] === "Track" ? "track" : "elective";
    const tracks = kind === "core" || !kindM[2] ? undefined : kindM[2].split(/[;,]/).map((t) => t.trim()).filter((t) => TRACKS.includes(t));
    const objectives = [];
    const objStart = card.indexOf("**Obiective:**");
    if (objStart >= 0) {
      for (const line of card.slice(objStart).split("\n").slice(1)) {
        const o = line.match(/^\s+\d+\.\s+(.+)$/);
        if (o) objectives.push(o[1].trim());
        else if (line.startsWith("- **")) break;
      }
    }
    const prereqText = field(card, "Se sprijină pe");
    const prereqs = [...prereqText.matchAll(/\b(\d)\.(\d{1,2})(?:\.(\d{1,2}))?\b/g)].map((x) => (x[3] ? `${x[1]}.${x[2]}.${x[3]}` : `${x[1]}.${x[2]}`));
    const conceptText = field(card, "Concepte").replace(/\([^)]*\)/g, "").replace(/✓/g, "");
    const termText = field(card, "Termeni noi de glosar");
    lessons.push({
      id: `${h[1]}.${h[2]}.${h[3]}`,
      unit: `${h[1]}.${h[2]}`,
      title: h[4].trim(),
      legacy: h[5],
      stage: stage.toLowerCase(),
      minutes: Number((mins || "").replace(/\D/g, "")) || 6,
      kind,
      tracks,
      objectives,
      concepts: ids(conceptText),
      prereqs: [...new Set(prereqs)],
      terms: termText.startsWith("—") ? [] : [...termText.matchAll(/`([a-z0-9-]+)`/g)].map((x) => x[1]),
    });
  }
}

const LEVELS = [
  { id: 0, name: "Orientation", tagline: "What a market is, and how to think when outcomes are uncertain." },
  { id: 1, name: "Foundations", tagline: "Read a chart, place an order, size a trade and keep a plan." },
  { id: 2, name: "Practitioner", tagline: "Tools, setups and routines that hold up across market regimes." },
  { id: 3, name: "Advanced", tagline: "Market internals, macro, statistics and system design." },
  { id: 4, name: "Professional", tagline: "Derivatives, execution at scale and the business of trading." },
];

const levels = LEVELS.map((lv) => ({
  ...lv,
  units: [...units.values()]
    .filter((u) => u.level === lv.id)
    .sort((a, b) => Number(a.id.split(".")[1]) - Number(b.id.split(".")[1]))
    .map((u) => ({ ...u, lessons: lessons.filter((l) => l.unit === u.id).sort((a, b) => Number(a.id.split(".")[2]) - Number(b.id.split(".")[2])) })),
}));

const ts = `// Generated by packages/academy/scripts/course-from-docs.cjs from docs/learn/course. Don't edit by hand.
import type { CourseLevel } from "./types";

export const COURSE_LEVELS: CourseLevel[] = ${JSON.stringify(levels, null, 1).replace(/\n\s*/g, " ")};
`;
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, ts);
console.log(`levels ${levels.length}, units ${units.size}, lessons ${lessons.length}, legacy ${lessons.filter((l) => l.legacy).length}`);
